# Renders assets/tray-icon.svg into the PNGs the tray icon uses, one per state, and
# writes them to src/tray/icons.ts. Run it on Windows after changing the SVG:
#   powershell -NoProfile -ExecutionPolicy Bypass -STA -File scripts/render-tray-icons.ps1
#
# It draws with WPF, which ships with Windows, and supports what the icon uses: <path>
# elements with fill, stroke and stroke-width, inside <g> elements with translate()
# and scale() transforms. The element with id="badge" is recoloured for each state.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName PresentationCore, WindowsBase

$root = Split-Path -Parent $PSScriptRoot
$svg = [xml](Get-Content (Join-Path $root 'assets/tray-icon.svg') -Raw)

# Badge colour for each state; idle keeps the SVG's own
$states = [ordered]@{ idle = $null; syncing = '#0078D4'; attention = '#C42B1C' }
# 32 px for the Windows notification area, 64 px for the macOS menu bar and Linux panels
$sizes = 32, 64

function New-Brush([string]$color) {
  if (-not $color -or $color -eq 'none') { return $null }
  return New-Object System.Windows.Media.SolidColorBrush ([System.Windows.Media.ColorConverter]::ConvertFromString($color))
}

# WPF's path syntax is SVG's, but its parser needs numbers like "2.9.2" (2.9 and .2) apart
function Get-Geometry([string]$data) {
  $tokens = [regex]::Matches($data, '[a-zA-Z]|-?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?') | ForEach-Object { $_.Value }
  return [System.Windows.Media.Geometry]::Parse($tokens -join ' ')
}

function Draw-Children($dc, $node, [string]$badge) {
  foreach ($child in $node.ChildNodes) {
    if ($child.LocalName -eq 'path') {
      $fill = if ($badge -and $child.id -eq 'badge') { $badge } else { $child.fill }
      $pen = $null
      if ($child.stroke -and $child.stroke -ne 'none') {
        $width = if ($child.'stroke-width') { [double]$child.'stroke-width' } else { 1.0 }
        $pen = New-Object System.Windows.Media.Pen (New-Brush $child.stroke), $width
        $pen.LineJoin = [System.Windows.Media.PenLineJoin]::Round
      }
      $dc.DrawGeometry((New-Brush $fill), $pen, (Get-Geometry $child.d))
    } elseif ($child.LocalName -eq 'g') {
      # SVG applies the rightmost transform first; WPF applies the last one pushed first
      $pushed = 0
      foreach ($t in [regex]::Matches([string]$child.transform, '(translate|scale)\(([^)]*)\)')) {
        $args2 = $t.Groups[2].Value -split '[\s,]+' | Where-Object { $_ } | ForEach-Object { [double]$_ }
        if ($t.Groups[1].Value -eq 'translate') {
          $dc.PushTransform((New-Object System.Windows.Media.TranslateTransform $args2[0], ($args2 + 0)[1]))
        } else {
          $sy = if ($args2.Count -gt 1) { $args2[1] } else { $args2[0] }
          $dc.PushTransform((New-Object System.Windows.Media.ScaleTransform $args2[0], $sy))
        }
        $pushed++
      }
      Draw-Children $dc $child $badge
      for ($i = 0; $i -lt $pushed; $i++) { $dc.Pop() }
    }
  }
}

function Render-Png([int]$size, [string]$badge) {
  $viewBox = $svg.svg.viewBox -split '\s+' | ForEach-Object { [double]$_ }
  $visual = New-Object System.Windows.Media.DrawingVisual
  $dc = $visual.RenderOpen()
  $dc.PushTransform((New-Object System.Windows.Media.ScaleTransform ($size / $viewBox[2]), ($size / $viewBox[3])))
  $dc.PushTransform((New-Object System.Windows.Media.TranslateTransform (-$viewBox[0]), (-$viewBox[1])))
  Draw-Children $dc $svg.svg $badge
  $dc.Pop(); $dc.Pop()
  $dc.Close()

  $bitmap = New-Object System.Windows.Media.Imaging.RenderTargetBitmap $size, $size, 96, 96, ([System.Windows.Media.PixelFormats]::Pbgra32)
  $bitmap.Render($visual)
  $encoder = New-Object System.Windows.Media.Imaging.PngBitmapEncoder
  $encoder.Frames.Add([System.Windows.Media.Imaging.BitmapFrame]::Create($bitmap))
  $stream = New-Object System.IO.MemoryStream
  $encoder.Save($stream)
  return [Convert]::ToBase64String($stream.ToArray())
}

$lines = @(
  '// Generated by scripts/render-tray-icons.ps1 from assets/tray-icon.svg; edit those instead.',
  '// PNGs, base64, for each tray state at 32 px (Windows) and 64 px (macOS, Linux).',
  'export const TRAY_ICONS = {'
)
foreach ($state in $states.Keys) {
  $lines += "  ${state}: {"
  foreach ($size in $sizes) { $lines += "    ${size}: `"$(Render-Png $size $states[$state])`"," }
  $lines += '  },'
}
$lines += '} as const;'
$out = Join-Path $root 'src/tray/icons.ts'
[System.IO.File]::WriteAllText($out, ($lines -join "`n") + "`n")
"Wrote $out"
